# 硬件与传感器参数 (Hardware and Sensor Parameters)
# 模块名称：config_dist_1080p (1080P Camera Distortion Correction Configuration)
# 基本功能：提供 1080P 分辨率相机畸变校正所需的硬件与传感器参数配置，为畸变校正算法提供数学参数基础，支持两种畸变模型的加权混合以优化校正效果。
# 基本介绍：
# - 包含视频与相机基本参数：定义 1080P 图像分辨率（1920x1080）、帧率（60FPS）等基础属性；
# - 相机内参矩阵（K）：提供共享的相机内参（焦距、主点坐标），作为畸变校正的几何基准；
# - 畸变模型混合配置：支持两种模型加权融合，提升校正精度：
# - 模型 A（基础模型）：基于 k1、k2 系数，作为校正主体，效果稳定；
# - 模型 B（k3 辅助模型）：增加 k3 系数，辅助校正基础模型难以处理的边缘畸变；
# - 通过权重参数（WEIGHT_BASE、WEIGHT_K3_ADDON）调配两种模型的贡献比例；
# - 校正后图像缩放系数（Undistortion Alpha）：控制校正后图像的裁剪与保留范围（0-1 之间），平衡边缘信息保留与黑边消除。
# 核心畸变校正数学处理逻辑：
# 基于相机内参矩阵建立图像坐标与物理坐标的映射关系，通过两种畸变模型的系数（k1、k2 及 k3）分别描述不同程度的径向畸变，再通过加权混合公式融合两种模型的校正结果，最终结合 alpha 系数调整输出图像范围，实现精准的畸变校正。
# 修正记录：
# 1. 改进版：新增两种畸变模型的加权混合机制，解决单一模型对边缘畸变校正不足的问题，提升整体校正效果。
