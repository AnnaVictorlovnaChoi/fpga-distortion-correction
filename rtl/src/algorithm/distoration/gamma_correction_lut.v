// gamma_correction_lut.v
// -----------------------------------------------------------------------------
// Gamma 校正模块 (用于 RGB565)
//
// 模块名称：gamma_correction_lut (Gamma Correction LUT Module for RGB565)
// 基本功能：实现 RGB565 格式图像的 Gamma 校正处理，通过预定义查找表（LUT）对图像的红（R）、绿（G）、蓝（B）通道进行非线性亮度调整，解决硬件感光度提升后的过曝问题。
// 基本介绍：
// 采用 2 级流水线设计，S0 级寄存输入数据与有效信号，S1 级通过 LUT 完成 Gamma 计算并寄存输出，保证时序性能；
// 通道 LUT 配置：R/B 通道共享 5bit 输入转 5bit 输出的 LUT，G 通道单独使用 6bit 输入转 6bit 输出的 LUT，均适配 Gamma 1.4；
// LUT 生成规则：R/B 通道基于公式 round ((i/31.0)(1/1.4) * 31) 生成（i 取值 0-31），G 通道基于公式 round ((i/63.0)(1/1.4) * 63) 生成（i 取值 0-63）；
// 包含复位逻辑，复位时清空内部寄存器与输出，确保模块启动时状态稳定；
// 接口适配：输入 i_valid 信号同步图像数据，输出 o_valid 信号与校正后的 RGB565 数据，保证数据时序对齐。
// 修正记录：
// (V1.1) 设计 2 级流水线结构，提升模块时序性能；
// (V1.3) 关键修正：为防止硬件感光度提升后的过曝，将 Gamma 值从 1.8/1.6 降至 1.4；更新 R/G/B 通道 LUT 的 initial 初始化块；保持 2 级流水线与复位逻辑。
// 设计人员：王博
// 最后修改时间：2025-11-05
// -----------------------------------------------------------------------------

module gamma_correction_lut (
    input  wire         clk,
    input  wire         rst_n,
    
    input  wire         i_valid,
    input  wire [15:0]  i_data_rgb565,
    
    output reg          o_valid,
    output reg  [15:0]  o_data_rgb565
);

    // --- 输入/输出分离 ---
    reg  [4:0]  r_in_s0, b_in_s0;
    reg  [5:0]  g_in_s0;
    reg         valid_s0;
    
    wire [4:0]  r_out_s1, b_out_s1;
    wire [5:0]  g_out_s1;
    
    // --- S0: 寄存输入 (第1级流水线) ---
    always @(posedge clk) begin
        if (!rst_n) begin
            valid_s0 <= 1'b0;
            r_in_s0  <= 5'd0;
            g_in_s0  <= 6'd0;
            b_in_s0  <= 5'd0;
        end else begin
            valid_s0 <= i_valid;
            if (i_valid) begin
                {r_in_s0, g_in_s0, b_in_s0} <= i_data_rgb565;
            end
        end
    end

    // --- S1: Gamma LUT (ROMs) ---
    
    // R/B LUT (5-bit -> 5-bit) for Gamma 1.4
    // (Generated by: round((i/31.0)**(1/1.4) * 31) for i in 0..31)
    reg [4:0] rom_r_b [0:31];
    initial begin
        rom_r_b[ 0] = 5'd0;  rom_r_b[ 1] = 5'd4;  rom_r_b[ 2] = 5'd6;  rom_r_b[ 3] = 5'd8;
        rom_r_b[ 4] = 5'd9;  rom_r_b[ 5] = 5'd11; rom_r_b[ 6] = 5'd12; rom_r_b[ 7] = 5'd13;
        rom_r_b[ 8] = 5'd14; rom_r_b[ 9] = 5'd15; rom_r_b[10] = 5'd16; rom_r_b[11] = 5'd17;
        rom_r_b[12] = 5'd18; rom_r_b[13] = 5'd19; rom_r_b[14] = 5'd19; rom_r_b[15] = 5'd20;
        rom_r_b[16] = 5'd21; rom_r_b[17] = 5'd22; rom_r_b[18] = 5'd22; rom_r_b[19] = 5'd23;
        rom_r_b[20] = 5'd24; rom_r_b[21] = 5'd24; rom_r_b[22] = 5'd25; rom_r_b[23] = 5'd26;
        rom_r_b[24] = 5'd26; rom_r_b[25] = 5'd27; rom_r_b[26] = 5'd27; rom_r_b[27] = 5'd28;
        rom_r_b[28] = 5'd28; rom_r_b[29] = 5'd29; rom_r_b[30] = 5'd30; rom_r_b[31] = 5'd31;
    end
    
    // G LUT (6-bit -> 6-bit) for Gamma 1.4
    // (Generated by: round((i/63.0)**(1/1.4) * 63) for i in 0..63)
    reg [5:0] rom_g [0:63];
    initial begin
        rom_g[ 0] = 6'd0;  rom_g[ 1] = 6'd6;  rom_g[ 2] = 6'd9;  rom_g[ 3] = 6'd11;
        rom_g[ 4] = 6'd13; rom_g[ 5] = 6'd15; rom_g[ 6] = 6'd17; rom_g[ 7] = 6'd18;
        rom_g[ 8] = 6'd20; rom_g[ 9] = 6'd21; rom_g[10] = 6'd23; rom_g[11] = 6'd24;
        rom_g[12] = 6'd25; rom_g[13] = 6'd27; rom_g[14] = 6'd28; rom_g[15] = 6'd29;
        rom_g[16] = 6'd30; rom_g[17] = 6'd31; rom_g[18] = 6'd32; rom_g[19] = 6'd33;
        rom_g[20] = 6'd34; rom_g[21] = 6'd35; rom_g[22] = 6'd36; rom_g[23] = 6'd37;
        rom_g[24] = 6'd38; rom_g[25] = 6'd39; rom_g[26] = 6'd40; rom_g[27] = 6'd41;
        rom_g[28] = 6'd41; rom_g[29] = 6'd42; rom_g[30] = 6'd43; rom_g[31] = 6'd44;
        rom_g[32] = 6'd45; rom_g[33] = 6'd45; rom_g[34] = 6'd46; rom_g[35] = 6'd47;
        rom_g[36] = 6'd48; rom_g[37] = 6'd48; rom_g[38] = 6'd49; rom_g[39] = 6'd50;
        rom_g[40] = 6'd50; rom_g[41] = 6'd51; rom_g[42] = 6'd52; rom_g[43] = 6'd52;
        rom_g[44] = 6'd53; rom_g[45] = 6'd53; rom_g[46] = 6'd54; rom_g[47] = 6'd55;
        rom_g[48] = 6'd55; rom_g[49] = 6'd56; rom_g[50] = 6'd56; rom_g[51] = 6'd57;
        rom_g[52] = 6'd57; rom_g[53] = 6'd58; rom_g[54] = 6'd58; rom_g[55] = 6'd59;
        rom_g[56] = 6'd59; rom_g[57] = 6'd60; rom_g[58] = 6'd60; rom_g[59] = 6'd61;
        rom_g[60] = 6'd61; rom_g[61] = 6'd62; rom_g[62] = 6'd62; rom_g[63] = 6'd63;
    end
    
    assign r_out_s1 = rom_r_b[r_in_s0];
    assign g_out_s1 = rom_g[g_in_s0];
    assign b_out_s1 = rom_r_b[b_in_s0];
    
    // --- S1: 寄存输出 (第2级流水线) ---
    always @(posedge clk) begin
        if (!rst_n) begin
            o_valid       <= 1'b0;
            o_data_rgb565 <= 16'd0;
        end else begin
            o_valid       <= valid_s0;
            o_data_rgb565 <= {r_out_s1, g_out_s1, b_out_s1};
        end
    end

endmodule
