import numpy as np

# 1. 视频与相机基本参数
IMG_WIDTH = 1920
IMG_HEIGHT = 1080
FPS = 60.0

# 2. 相机内参矩阵 (Camera Intrinsic Matrix, K)
# (此参数对两个模型是共享的)
CAMERA_MATRIX = np.array([
    [892.2344, 0.      , 964.9090],
    [0.      , 889.7341, 552.7384],
    [0.      , 0.      , 1.      ]
])

# -----------------------------------------------------------------------------
# 畸变模型混合配置 (Distortion Model Blending Configuration)
# -----------------------------------------------------------------------------

# --- 模型A: 基础模型 (k1, k2) ---
# 这是您现有的、效果较好的模型，作为校正的主体。
DIST_COEFFS_BASE = np.array([-0.2817, 0.0593, 0.0, 0.0, 0.0])
# 权重 (例如 70%)
WEIGHT_BASE = 0.71

# --- 模型B: k3模型 (k1, k2, k3) ---
# 该模型用于辅助校正 "基础模型" 无法处理的边缘畸变。
# 您需要在此处填入一个估算的 k3 值。
#
# !!【重要】k3调优提示 !!
# 桶形畸变 (Barrel): k1 < 0。如果边缘校正不足，k3 通常也为负数。
# 枕形畸变 (Pincushion): k1 > 0。
# 您的 k1 = -0.2817 (强桶形)，k2 = 0.0593 (对抗k1)
# 猜测您的边缘校正不足，需要一个负的 k3 来增强边缘的拉伸。
#
# *** 请从一个较小的值开始尝试，例如 -0.005 ***
K3_GUESS = -0.0225
DIST_COEFFS_K3_ADDON = np.array([-0.3217, 0.1093, 0.0, 0.0, K3_GUESS])
# 权重 (例如 30%)
WEIGHT_K3_ADDON = 0.29

# 4. 校正后图像缩放系数 (Undistortion Alpha)
# (此参数对两个模型是共享的)
# - alpha = 1: 保留所有原始像素，但图像边缘可能会有黑色区域。
# - alpha = 0: 裁剪掉所有因校正产生的黑色区域，可能会丢失部分图像信息。
UNDISTORT_ALPHA = 0.9